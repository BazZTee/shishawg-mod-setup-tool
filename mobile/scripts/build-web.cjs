// Builds mobile/www: the desktop renderer plus one bundle that contains the
// desktop main process (src/main) with browser replacements for Node/Electron.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const esbuild = require('esbuild');

const mobile = path.resolve(__dirname, '..');
const root = path.resolve(mobile, '..');
const www = path.join(mobile, 'www');
const shims = path.join(mobile, 'shims');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

// 1. Assemble renderer.js and the IPC contract exactly like the desktop build.
execFileSync(process.execPath, [path.join(root, 'scripts/build-renderer.cjs')], { stdio: 'inherit' });

// 2. Bundled read-only files the main process reads with fs (virtual paths).
const assets = {
  '/app/src/main/hookahtools_tobacco_snapshot.json': 'src/main/hookahtools_tobacco_snapshot.json',
  '/app/docs/qna.html': 'docs/qna.html',
  '/app/docs/overlay.html': 'docs/overlay.html'
};
const seed = {};
for (const [virtualPath, file] of Object.entries(assets)) {
  const full = path.join(root, file);
  if (fs.existsSync(full)) seed[virtualPath] = fs.readFileSync(full, 'utf8');
}
fs.writeFileSync(path.join(mobile, 'src/generated-assets.js'),
  '// GENERATED by mobile/scripts/build-web.cjs\nmodule.exports = ' + JSON.stringify(seed) + ';\n');

// 3. Fresh www with the renderer files.
fs.rmSync(www, { recursive: true, force: true });
fs.cpSync(path.join(root, 'src/renderer'), www, {
  recursive: true,
  filter: (src) => !src.includes(path.join('renderer', 'modules'))
});
fs.mkdirSync(path.join(www, 'build'), { recursive: true });
fs.copyFileSync(path.join(root, 'build/icon.png'), path.join(www, 'build/icon.png'));

// 4. Main-process bundle.
const alias = {
  electron: path.join(shims, 'electron.js'),
  'electron-updater': path.join(shims, 'electron-updater.js'),
  fs: path.join(shims, 'fs.js'),
  http: path.join(shims, 'http.js'),
  https: path.join(shims, 'https.js'),
  url: path.join(shims, 'url.js'),
  ws: path.join(shims, 'ws.js'),
  crypto: path.join(shims, 'crypto.js'),
  zlib: path.join(shims, 'zlib.js'),
  path: require.resolve('path-browserify'),
  events: require.resolve('events/'),
  buffer: require.resolve('buffer/'),
  stream: require.resolve('stream-browserify')
};

esbuild.buildSync({
  entryPoints: [path.join(mobile, 'src/entry.js')],
  outfile: path.join(www, 'android-bridge.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome100'],
  alias,
  inject: [path.join(shims, 'process-globals.js')],
  define: {
    __dirname: JSON.stringify('/app/src/main'),
    __APP_VERSION__: JSON.stringify(pkg.version),
    'process.env.NODE_ENV': '"production"'
  },
  logLevel: 'warning',
  legalComments: 'none',
  minify: process.argv.includes('--minify'),
  sourcemap: process.argv.includes('--sourcemap') ? 'inline' : false
});

// 5. Load the bridge before every renderer script and add mobile styles.
const indexPath = path.join(www, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const firstScript = '<script src="fuzzy.js"></script>';
if (!html.includes(firstScript)) throw new Error('index.html: Einstiegspunkt für die Android-Brücke nicht gefunden.');
html = html
  .replace('src="../../build/icon.png"', 'src="build/icon.png"')
  .replace('</head>', '  <link rel="stylesheet" href="android.css">\n</head>')
  .replace(firstScript, '<script src="android-bridge.js"></script>\n  ' + firstScript);
fs.writeFileSync(indexPath, html);
fs.copyFileSync(path.join(mobile, 'src/android.css'), path.join(www, 'android.css'));

console.log(`Android-Weboberfläche ${pkg.version} in mobile/www erstellt.`);
