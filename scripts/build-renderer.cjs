// Reproducible, dependency-free assembly. Edit modules, never renderer.js.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'src/renderer/modules');
const files = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
const banner = '// GENERATED by scripts/build-renderer.cjs. Edit src/renderer/modules.\n';
const code = files.map(file => fs.readFileSync(path.join(dir, file), 'utf8')).join('');
fs.writeFileSync(path.join(root, 'src/renderer/renderer.js'), banner + code);
const contract = JSON.parse(fs.readFileSync(path.join(root, 'src/shared/ipc-contract.json'), 'utf8'));
const preload = fs.readFileSync(path.join(root, 'src/main/preload.template.cjs'), 'utf8')
  .replace('__INVOKE_CHANNELS__', JSON.stringify(contract.invoke))
  .replace('__EVENT_CHANNELS__', JSON.stringify(contract.events));
fs.writeFileSync(path.join(root, 'src/main/preload.js'), banner + preload);
console.log(`Assembled ${files.length} feature modules and sandboxed IPC bridge.`);
